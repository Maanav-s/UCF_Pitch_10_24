#!/usr/bin/env python3
"""Generate packets.h for the C++ trader from tools/fix_test_packet.py.

Usage (from host/):  python dump_packets.py
Writes packets.h next to this script. Re-run it, then rebuild the .exe,
whenever fix_test_packet.py changes.
"""
import os
import sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, "..", "tools"))
from fix_test_packet import buy_order, market_data  # noqa: E402


def c_array(name, data):
    rows = []
    for i in range(0, len(data), 12):
        rows.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]))
    return f"static const unsigned char {name}[] = {{\n" + ",\n".join(rows) + "\n};\n"


md, reply = market_data(), buy_order()
out = os.path.join(here, "packets.h")
with open(out, "w") as f:
    f.write("// Generated by dump_packets.py from tools/fix_test_packet.py. Do not edit.\n")
    f.write("#pragma once\n\n")
    f.write(f"// market data the exchange sends ({len(md)} bytes)\n")
    f.write(c_array("MD_BYTES", md) + "\n")
    f.write(f"// buy reply we send back ({len(reply)} bytes)\n")
    f.write(c_array("REPLY_BYTES", reply))
print(f"wrote {out}: MD_BYTES {len(md)} bytes, REPLY_BYTES {len(reply)} bytes")